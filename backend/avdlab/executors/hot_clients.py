"""Phase 6 (C): interactive test hosts — hot-add / remove a linux client on a running containerlab lab.

Flow of `POST /labs/{id}/clients` (routes in `client_routes.py`):
  API   `add_endpoint` op (topology/edit.py, so AVD inputs + topology stay truthful) → `build_devices` (labs/build.py:
        only the affected switch(es) + related devices are rebuilt; clab topology + clients.json regenerated)
  job   `lab.client_deploy`:
        1. sync the lab dir, push the new intended config with `arista.eos.eos_config` (replace: config) from the
           agent container on the clab mgmt network, `--limit` to the switches whose config changed
        2. `docker run -d --name <client> --network none --label avdlab.lab=<slug> --label avdlab.role=client
           --cap-add NET_ADMIN --cap-add NET_RAW <image> sleep infinity` (caps: the setup script configures links/IPs)
        3. `containerlab tools veth create -a <switch>:ethN -b <client>:eth1` (prefix '' → container name = node name)
           then `show interfaces status` on the switch must list EthernetN. A hot-added port is NOT in the
           EosIntfMapping.json the switch booted with, so cEOS uses its default mapping (ethN → EthernetN, eth1_1 →
           Ethernet1/1); when the port does not show up the job logs a warning (the result carries
           `interface_visible: false`) — a full redeploy (the port is then in the mapping) always fixes it.
        4. the generated setup script (topology/clients.py) runs inside the client (`docker exec -i … sh -s`)
        5. ping the default gateway (SVI virtual IP) → `reachable`
  `lab.client_remove`: `docker rm -f` (deleting the container deletes the veth pair) + config push of the switch(es)
  whose config changed after the `remove_endpoint` op (applied by the API).

Hot-added clients are tracked in `lab.settings["hot_clients"][name]` ({switch, port, vlans, mode, ip, image,
deployed, ...}); their explicit IP / image are re-applied after every topology regeneration
(`clients.apply_client_overrides`), so a later full redeploy recreates the client identically.
"""
from __future__ import annotations

