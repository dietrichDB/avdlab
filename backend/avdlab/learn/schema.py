"""Schema browser: lookup + fuzzy search over the vendored AVD 6.4 schema export (`learn/schema/*.json`,
regenerated by `scripts/export_schema.py` from the AVD repo checkout; the pyavd wheel only ships pickles).

Paths are dotted, list items without an index: `router_bgp.peer_groups.name`. Accepted spellings are normalised:
`l3leaf.defaults.loopback_ipv4_pool`, `l3leaf.node_groups[].nodes[0].id`, `router_bgp.peer_groups.[].name`,
`tenants[name=T].vrfs`. Default dynamic keys are aliased (`l3leaf` → `<node_type_keys.key>`, `servers` →
`<connected_endpoints_keys.key>`, `tenants` → `<network_services_keys.name>`).
"""
from __future__ import annotations

import json
import re
from difflib import SequenceMatcher
from functools import lru_cache
from pathlib import Path
from typing import Any

SCHEMA_DIR = Path(__file__).parent / "schema"
SCHEMA_NAMES = ("eos_designs", "eos_cli_config_gen")
DOC_BASE = "https://avd.arista.com/6.4/ansible_collections/arista/avd/roles/{role}/docs"


class SchemaKeyError(KeyError):
    def __init__(self, key: str, suggestions: list[str]):
        super().__init__(key)
        self.key = key
        self.suggestions = suggestions


@lru_cache(maxsize=4)
def load(name: str) -> dict[str, Any]:
    if name not in SCHEMA_NAMES:
        raise ValueError(f"unknown schema {name!r}; one of {SCHEMA_NAMES}")
    return json.loads((SCHEMA_DIR / f"{name}.json").read_text())


def normalize_key(key: str) -> str:
    k = (key or "").strip().strip(".")
    k = re.sub(r"\[[^\]]*\]", "", k)          # [0], [], [name=x]
    k = re.sub(r"\.\d+(?=\.|$)", "", k)        # .0.
    k = re.sub(r"\.{2,}", ".", k)
    return k.strip(".")


def _resolve(doc: dict[str, Any], key: str) -> tuple[str, str]:
    """(display key, internal node path) – applies the dynamic-key aliases on the first segment."""
    k = normalize_key(key)
    head, _, rest = k.partition(".")
    alias = doc.get("aliases", {}).get(head)
    internal = f"{alias}.{rest}" if alias and rest else (alias or k)
    return k, internal


def doc_urls(name: str, table: str | None) -> tuple[str | None, str | None]:
    """(tables page, data-models section) URLs for a documentation table."""
    if not table:
        return None, None
    role = "eos_designs" if name == "eos_designs" else "eos_cli_config_gen"
    base = DOC_BASE.format(role=role)
    slug = load(name).get("sections", {}).get(table)
    return f"{base}/tables/{table}.html", (f"{base}/data-models.html#{slug}" if slug else None)


def _default_table(doc: dict[str, Any], internal: str) -> str | None:
    """eos_cli_config_gen documents each top-level key in `tables/<key with - >.md` without documentation_options."""
    guess = internal.split(".", 1)[0].replace("_", "-")
    return guess if guess in doc.get("sections", {}) else None


def _short(desc: str | None, limit: int = 140) -> str:
    if not desc:
        return ""
    first = desc.strip().split("\n", 1)[0]
    return first if len(first) <= limit else first[: limit - 1] + "…"


def lookup(name: str, key: str) -> dict[str, Any]:
    doc = load(name)
    nodes = doc["nodes"]
    display, internal = _resolve(doc, key)
    if not display:  # root: list the top-level keys
        return {"schema": name, "key": "", "type": "dict", "description": "Top-level keys", "default": None,
                "valid_values": None, "min": None, "max": None, "required": False, "deprecation": None,
                "keys": [{"name": k, "type": (nodes.get(k) or {}).get("t"), "short": _short((nodes.get(k) or {}).get("d"))}
                         for k in doc.get("top", [])] + [{"name": a, "type": "dict", "short": f"alias of {t}"}
                                                          for a, t in sorted(doc.get("aliases", {}).items())],
                "items": None, "doc_url": None, "section_url": None, "table": None, "eos_cli_config_gen_ref": None,
                "alias_of": None, "format": None, "pattern": None, "primary_key": None}
    node = nodes.get(internal)
    if node is None:
        raise SchemaKeyError(display, [m["key"] for m in search(name, display.split(".")[-1], limit=8)])
    children = []
    for child in node.get("k", []):
        c = nodes.get(f"{internal}.{child}") or {}
        children.append({"name": child, "type": c.get("t") if c.get("t") != "list" else f"list[{c.get('it')}]",
                         "short": _short(c.get("d")), "required": bool(c.get("req")),
                         "deprecated": bool(c.get("dep"))})
    items = None
    if node.get("t") == "list":
        items = {"type": node.get("it"), "primary_key": node.get("pk"), "valid_values": node.get("ivv"),
                 "format": node.get("ifmt"), "pattern": node.get("ipat")}
    doc_url, section_url = doc_urls(name, node.get("tbl") or _default_table(doc, internal))
    return {
        "schema": name,
        "key": display,
        "type": node.get("t"),
        "description": node.get("d"),
        "default": node.get("df"),
        "valid_values": node.get("vv"),
        "min": node.get("min"),
        "max": node.get("max"),
        "required": bool(node.get("req")),
        "deprecation": node.get("dep"),
        "format": node.get("fmt"),
        "pattern": node.get("pat"),
        "primary_key": node.get("pk"),
        "keys": children,
        "items": items,
        "table": node.get("tbl"),
        "doc_url": doc_url,
        "section_url": section_url,
        "eos_cli_config_gen_ref": node.get("ref"),
        "alias_of": internal if internal != display else None,
    }


def _display(doc: dict[str, Any], internal: str) -> str:
    """Internal path → the friendliest display path (alias for the default dynamic keys)."""
    for dyn, pretty in (("<node_type_keys.key>", "l3leaf"), ("<connected_endpoints_keys.key>", "servers"),
                        ("<network_services_keys.name>", "tenants")):
        if internal == dyn or internal.startswith(dyn + "."):
            return pretty + internal[len(dyn):]
    return internal


@lru_cache(maxsize=2)
def _index(name: str) -> list[tuple[str, str, str, str]]:
    """[(display path, lowercase path, lowercase leaf, lowercase short description)]"""
    doc = load(name)
    out = []
    for path, node in doc["nodes"].items():
        if path.startswith("<custom_"):
            continue
        disp = _display(doc, path)
        out.append((disp, disp.lower(), disp.rsplit(".", 1)[-1].lower(), _short(node.get("d"), 200).lower()))
    return out


def search(name: str, q: str, limit: int = 25) -> list[dict[str, Any]]:
    """Fuzzy match on the key path (exact leaf > leaf prefix > path substring > token overlap > similarity),
    shorter paths first; description matches rank below key matches."""
    q = normalize_key(q).lower()
    if not q:
        return []
    tokens = [t for t in re.split(r"[\s._-]+", q) if t]
    doc = load(name)
    scored: list[tuple[float, str]] = []
    for disp, low, leaf, desc in _index(name):
        score = 0.0
        if leaf == q:
            score = 100
        elif low == q or low.endswith("." + q):
            score = 95
        elif leaf.startswith(q):
            score = 80
        elif q in low:
            score = 65
        elif tokens and all(t in low for t in tokens):
            score = 55
        elif tokens and all(t in desc for t in tokens):
            score = 30
        else:
            ratio = SequenceMatcher(None, q, leaf).ratio()
            if ratio >= 0.75:
                score = 40 * ratio
        if score:
            penalty = 6 if disp.startswith(("devices.", "device_profiles.")) else 0  # PREVIEW models rank last
            penalty += 2 if (".node_groups." in disp or ".nodes." in disp) else 0  # prefer `<type>.defaults.<key>`
            scored.append((score - penalty - disp.count(".") * 1.5 - len(disp) / 200, disp))
    scored.sort(key=lambda x: (-x[0], x[1]))
    out = []
    seen: set[str] = set()
    for score, disp in scored:
        if disp in seen:
            continue
        seen.add(disp)
        _d, internal = _resolve(doc, disp)
        node = doc["nodes"].get(internal) or {}
        out.append({"schema": name, "key": disp, "type": node.get("t"), "short": _short(node.get("d")),
                    "score": round(score, 1)})
        if len(out) >= limit:
            break
    return out
